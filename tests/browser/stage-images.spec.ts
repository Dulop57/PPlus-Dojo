import {test,expect,type Page} from '@playwright/test';
import {readFile} from 'node:fs/promises';
const imageStyle=(page:Page)=>page.locator('.stage-header-art img').getAttribute('style');
test.beforeEach(()=>{test.skip(process.env.VITE_DOJO_IMAGE_EDITOR!=='true','Image editor requires explicit local opt-in.');});

test('Slider changes save to the project file without pressing Done',async({page})=>{
  await page.goto('/#/stages/battlefield');
  await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  const saved=page.waitForResponse(response=>response.url().endsWith('/__dojo-owner/stage-framing')&&response.request().method()==='POST');
  await page.getByRole('slider',{name:'Battlefield image scale'}).fill('1.75');
  expect((await saved).ok()).toBe(true);
  await expect(page.getByText('Saved to project.',{exact:true})).toBeVisible();
  const defaults=JSON.parse(await readFile('artifacts/image-editor-test-defaults.json','utf8'));
  expect(defaults.battlefield.scale).toBe(1.75);
  await page.reload();
  await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  await expect(page.getByRole('slider',{name:'Battlefield image scale'})).toHaveValue('1.75');
});
test('Live banner framing is identical after automatic project save and reload',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/#/stages/battlefield');
  await expect(page.getByRole('button',{name:'Adjust image',exact:true})).toBeEnabled();
  const banner=await page.locator('.stage-title').boundingBox();
  await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  expect(await page.locator('.stage-title').boundingBox()).toEqual(banner);
  await expect(page.getByRole('slider',{name:'Battlefield image horizontal'})).toBeDisabled();
  await page.getByRole('slider',{name:'Battlefield image scale'}).fill('1.5');
  await page.getByRole('slider',{name:'Battlefield image horizontal'}).fill('25');
  await page.getByRole('slider',{name:'Battlefield image vertical'}).fill('-15');
  const preview=await imageStyle(page);
  const previewBounds=await page.locator('.stage-header-art img').boundingBox();
  await page.getByRole('button',{name:'Done'}).click();
  await expect(page.getByText('Saved to project.')).toBeVisible();
  await expect(page.locator('.stage-image-editor')).toHaveCount(0);
  expect(await imageStyle(page)).toEqual(preview);
  expect(await page.locator('.stage-header-art img').boundingBox()).toEqual(previewBounds);
  expect(await page.locator('.stage-title').boundingBox()).toEqual(banner);
  await page.reload();await expect(page.getByRole('button',{name:'Adjust image',exact:true})).toBeEnabled();
  expect(await imageStyle(page)).toEqual(preview);
  await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  await page.getByRole('slider',{name:'Battlefield image scale'}).fill('1.5');
  await page.getByRole('button',{name:'Close',exact:true}).click();
  expect(await imageStyle(page)).toEqual(preview);
  await page.getByRole('button',{name:'Smashville',exact:true}).click();
  await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  await expect(page.getByRole('slider',{name:'Smashville image scale'})).toHaveValue('1');
  await page.getByRole('button',{name:'Battlefield',exact:true}).click();
  await expect(page.getByRole('button',{name:'Adjust image',exact:true})).toBeEnabled();
  expect(await imageStyle(page)).toEqual(preview);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('Dragging uses the whole image, clamps at its edges and responds immediately on reversing',async({page})=>{
  await page.goto('/#/stages/yoshis-story');
  await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  await page.getByRole('slider',{name:"Yoshi's Story image scale"}).fill('1.5');
  const art=page.locator('.stage-header-art'),image=art.locator('img'),box=(await art.boundingBox())!;
  const before=(await image.boundingBox())!;
  const x=box.x+box.width*.65,y=box.y+box.height*.3;
  await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+20,y+12);await page.mouse.up();
  const after=(await image.boundingBox())!;
  expect(after.x-before.x).toBeCloseTo(20,1);expect(after.y-before.y).toBeCloseTo(12,1);
  await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x,y+700);
  let edges=await image.boundingBox();expect(edges!.y).toBeCloseTo(box.y,1);
  await page.mouse.move(x,y+690);await page.mouse.up();
  edges=await image.boundingBox();expect(edges!.y).toBeCloseTo(box.y-10,1);
  await page.getByRole('slider',{name:"Yoshi's Story image horizontal"}).fill('100');
  await page.getByRole('slider',{name:"Yoshi's Story image vertical"}).fill('-100');
  edges=await image.boundingBox();
  const currentBox=(await art.boundingBox())!;
  expect(edges!.x).toBeCloseTo(currentBox.x,1);expect(edges!.y+edges!.height).toBeCloseTo(currentBox.y+currentBox.height,1);
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.getByRole('button',{name:'Done'}).click();
  await page.reload();await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  await expect(page.getByRole('slider',{name:"Yoshi's Story image scale"})).toHaveValue('1');
  await expect(page.getByRole('slider',{name:"Yoshi's Story image vertical"})).toHaveValue('0');
});

test('Overview crop matches the banner and allows selecting source areas',async({page})=>{
  await page.goto('/#/stages/golden-temple');
  await page.getByRole('button',{name:'Adjust image',exact:true}).click();
  await page.getByRole('slider',{name:'Golden Temple image scale'}).fill('1.5');
  const overview=page.locator('.stage-image-overview'),box=(await overview.boundingBox())!;
  await page.mouse.click(box.x+box.width*.5,box.y+box.height*.25);
  const crop=(await page.locator('.stage-image-crop').boundingBox())!;
  expect(crop.x).toBeGreaterThanOrEqual(box.x-.1);expect(crop.x+crop.width).toBeLessThanOrEqual(box.x+box.width+.1);
  expect(crop.y).toBeGreaterThanOrEqual(box.y-.1);expect(crop.y+crop.height).toBeLessThanOrEqual(box.y+box.height+.1);
  const previous=await imageStyle(page);
  await page.mouse.move(crop.x+crop.width*.7,crop.y+crop.height*.5);await page.mouse.down();
  expect(await imageStyle(page)).toEqual(previous);
  await page.mouse.up();
  const source=page.locator('.stage-header-art img'),art=(await page.locator('.stage-header-art').boundingBox())!,image=(await source.boundingBox())!;
  expect((crop.y-box.y)/box.height).toBeCloseTo((art.y-image.y)/image.height,2);
  expect(crop.height/box.height).toBeCloseTo(art.height/image.height,2);
  await expect(overview.getByRole('img')).toHaveAttribute('src',/PPlus_Stage_GoldenTemple/);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
